#!/usr/bin/env node
/**
 * Regenerate the glossary table in `docs/agents/CONTEXT.md` from
 * `packages/contracts/src/glossary.ts` (docs/DOCUMENTATION.md, decision 7;
 *). The table between `<!-- glossary:start -->` and
 * `<!-- glossary:end -->` is generated; edit the TypeScript, not the table.
 *
 *   node --import ./scripts/node-ts-resolve.mjs scripts/gen-glossary.mjs           # write
 *   node --import ./scripts/node-ts-resolve.mjs scripts/gen-glossary.mjs --check   # exit 1 when stale
 *
 * Every source a term names must exist; that is checked here, so a term
 * cannot cite a doc that is gone.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { GLOSSARY, glossaryTermSchema } from '../packages/contracts/src/glossary.ts';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(repoRoot, 'docs', 'agents', 'CONTEXT.md');
const START = '<!-- glossary:start -->';
const END = '<!-- glossary:end -->';

let errors = 0;
const seen = new Set();
for (const row of GLOSSARY) {
  const parsed = glossaryTermSchema.safeParse(row);
  if (!parsed.success) {
    console.error(`glossary: ${row.term}: ${parsed.error.issues.map((issue) => issue.message).join('; ')}`);
    errors += 1;
  }
  const key = row.term.toLowerCase();
  if (seen.has(key)) {
    console.error(`glossary: ${row.term} appears twice`);
    errors += 1;
  }
  seen.add(key);
  for (const source of row.sources) {
    if (!existsSync(join(repoRoot, source))) {
      console.error(`glossary: ${row.term} cites ${source}, which does not exist`);
      errors += 1;
    }
  }
}
if (errors > 0) process.exit(1);

const cell = (text) => text.replace(/\|/gu, '\\|');
const rows = GLOSSARY.map((row) => {
  const name = `**${cell(row.term)}**${row.aliases ? ` (${row.aliases.map(cell).join(', ')})` : ''}`;
  const sources = row.sources.map((source) => `\`${source}\``).join(', ');
  return `| ${name} | ${cell(row.meaning)} | ${sources} |`;
});
const generated = [
  START,
  'Generated by `scripts/gen-glossary.mjs` from `packages/contracts/src/glossary.ts`; `pnpm verify` fails when it is stale. Add a term there, with its source.',
  '',
  '| Term | Meaning | Source |',
  '| --- | --- | --- |',
  ...rows,
  END,
].join('\n');

const text = readFileSync(target, 'utf8');
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`CONTEXT.md needs the ${START} and ${END} markers under ## Glossary`);
  process.exit(1);
}
const next = text.slice(0, start) + generated + text.slice(end + END.length);
if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('docs/agents/CONTEXT.md glossary is stale: run pnpm docs:map and commit the result');
    process.exit(1);
  }
} else if (next !== text) {
  writeFileSync(target, next);
  console.log('CONTEXT.md glossary written');
}
