#!/usr/bin/env node
// Write the commit being built into services/control-plane/src/build-info.ts
//. The Worker compares it with the head of `main` once an hour and
// counts a failure when a push has not deployed in 45 minutes.
//
// Workers Builds sets WORKERS_CI_COMMIT_SHA. Outside it, `git rev-parse HEAD`.
// A local run changes a tracked file; do not commit that change.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
let commit = process.env.WORKERS_CI_COMMIT_SHA?.trim() ?? '';
if (!commit) {
  try {
    commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    commit = 'unknown';
  }
}
if (!/^[0-9a-f]{7,40}$/u.test(commit)) commit = 'unknown';

writeFileSync(join(root, 'services/control-plane/src/build-info.ts'), `// Generated by scripts/write-build-info.mjs during cf:build (meet#318).
export const BUILD_COMMIT: string = '${commit}';
`);
console.log(`build-info: ${commit}`);
