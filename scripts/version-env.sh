#!/usr/bin/env bash
# Shared marketing version + integer build number for Apple targets.
#
#   MARKETING  VERSION (hand-bumped; tags are v$VERSION)
#   BUILD      git rev-list --count HEAD  (monotonic, same on every machine)
#
# Source this from other scripts (bash):
#   # shellcheck source=version-env.sh
#   source "$(dirname "$0")/version-env.sh"
#
# Or print for shell eval / CI:
#   eval "$(./scripts/version-env.sh --export)"
#
# Write Config/Version.xcconfig (Config/Starlings.xcconfig includes it):
#   ./scripts/version-env.sh --write-xcconfig
#
# Stamp a built Info.plist from an Xcode Run Script phase (needs
# TARGET_BUILD_DIR + INFOPLIST_PATH from xcodebuild):
#   ./scripts/version-env.sh --stamp-plist
#
# Check a version string against the rules below and exit, without git (the
# pre-commit hook passes the staged VERSION):
#   ./scripts/version-env.sh --check 5.2.0
set -euo pipefail

_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/.." && pwd)"
_VERSION_FILE="$_ROOT/VERSION"
_XCCONFIG="$_ROOT/Config/Version.xcconfig"

_check_only=0
if [[ "${BASH_SOURCE[0]:-$0}" == "$0" && "${1:-}" == "--check" ]]; then
  _check_only=1
  MEET_VERSION="$(printf '%s' "${2:-}" | tr -d '[:space:]')"
else
  if [[ ! -f "$_VERSION_FILE" ]]; then
    echo "error: missing $_VERSION_FILE" >&2
    exit 1
  fi
  MEET_VERSION="$(tr -d '[:space:]' < "$_VERSION_FILE")"
fi
if [[ ! "$MEET_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-][0-9A-Za-z.-]+)?$ ]]; then
  echo "error: VERSION must look like 1.2.3 (got '$MEET_VERSION')" >&2
  exit 1
fi

# Minor and patch are single digits (rolling versions). Major is unbounded.
_ver_core="${MEET_VERSION%%[-+]*}"
IFS=. read -r _ver_maj _ver_min _ver_pat <<<"$_ver_core"
if [[ ! "$_ver_min" =~ ^[0-9]$ || ! "$_ver_pat" =~ ^[0-9]$ ]]; then
  echo "error: VERSION minor and patch must be single digits 0-9 (got '$MEET_VERSION')" >&2
  echo "       after X.Y.9 roll minor; after X.9.9 roll major to (X+1).0.0 — never X.10.0" >&2
  exit 1
fi
unset _ver_core _ver_maj _ver_min _ver_pat

if [[ "$_check_only" -eq 1 ]]; then
  exit 0
fi

# A shallow clone counts only the commits it was given, so `rev-list --count`
# answers confidently and wrongly — that is how the website came to advertise
# "build 1" while the same commit was build 285 anywhere with full history.
# A truncated count is worse than no count: it is monotonic-looking, it goes
# backwards between machines, and CFBundleVersion is the one number the
# updater and the App Store use to order builds.
if [[ "$(git -C "$_ROOT" rev-parse --is-shallow-repository 2>/dev/null || echo true)" == "true" ]]; then
  echo "error: shallow clone — build number would be wrong (fetch full history: git fetch --unshallow)" >&2
  exit 1
fi

MEET_BUILD="$(git -C "$_ROOT" rev-list --count HEAD 2>/dev/null || true)"
if [[ -z "${MEET_BUILD:-}" || ! "$MEET_BUILD" =~ ^[0-9]+$ ]]; then
  MEET_BUILD=0
fi

# Apple CFBundleVersion must be non-zero.
if [[ "$MEET_BUILD" -lt 1 ]]; then
  MEET_BUILD=1
fi

export MEET_VERSION MEET_BUILD

_write_xcconfig() {
  cat > "$_XCCONFIG" <<EOF
// Generated by scripts/version-env.sh — do not edit.
// MARKETING ← VERSION · BUILD ← git rev-list --count HEAD
MARKETING_VERSION = $MEET_VERSION
CURRENT_PROJECT_VERSION = $MEET_BUILD
EOF
}

_stamp_one() {
  local plist="$1"
  [[ -f "$plist" ]] || return 0
  # Delete + Add (never Set): PlistBuddy Set preserves the existing value's
  # type, so a numeric version would stay numeric — and NSNumber bundle
  # versions crash Metal's telemetry the moment Portrait/VFX effects start.
  /usr/libexec/PlistBuddy -c "Delete :CFBundleShortVersionString" "$plist" 2>/dev/null || true
  /usr/libexec/PlistBuddy -c "Add :CFBundleShortVersionString string $MEET_VERSION" "$plist"
  /usr/libexec/PlistBuddy -c "Delete :CFBundleVersion" "$plist" 2>/dev/null || true
  /usr/libexec/PlistBuddy -c "Add :CFBundleVersion string $MEET_BUILD" "$plist"
  echo "stamped $plist → $MEET_VERSION ($MEET_BUILD)"
}

_stamp_plist() {
  if [[ -z "${TARGET_BUILD_DIR:-}" || -z "${INFOPLIST_PATH:-}" ]]; then
    echo "error: --stamp-plist needs TARGET_BUILD_DIR and INFOPLIST_PATH (Xcode build phase)" >&2
    exit 1
  fi
  local plist="${TARGET_BUILD_DIR}/${INFOPLIST_PATH}"
  if [[ ! -f "$plist" ]]; then
    echo "warning: Info.plist not found yet at $plist — skipping stamp" >&2
    return 0
  fi
  _stamp_one "$plist"
}

_stamp_product() {
  if [[ -z "${TARGET_BUILD_DIR:-}" ]]; then
    echo "error: --stamp-product needs TARGET_BUILD_DIR" >&2
    exit 1
  fi
  if [[ -n "${INFOPLIST_PATH:-}" && -f "${TARGET_BUILD_DIR}/${INFOPLIST_PATH}" ]]; then
    _stamp_one "${TARGET_BUILD_DIR}/${INFOPLIST_PATH}"
  fi
  local product="${TARGET_BUILD_DIR}/${FULL_PRODUCT_NAME:-}"
  if [[ -d "$product" ]]; then
    _stamp_one "$product/Contents/Info.plist"
    _stamp_one "$product/Info.plist"
  fi
}

# Only parse CLI flags when this file is executed (not sourced).
_executed=0
if [[ -n "${BASH_VERSION:-}" && "${BASH_SOURCE[0]}" == "$0" ]]; then
  _executed=1
fi

if [[ "$_executed" -eq 1 ]]; then
  case "${1:-}" in
    --export)
      printf 'export MEET_VERSION=%q\n' "$MEET_VERSION"
      printf 'export MEET_BUILD=%q\n' "$MEET_BUILD"
      ;;
    --print)
      echo "$MEET_VERSION+$MEET_BUILD"
      ;;
    --write-xcconfig)
      _write_xcconfig
      echo "wrote $_XCCONFIG ($MEET_VERSION+$MEET_BUILD)"
      ;;
    --stamp-plist)
      _stamp_plist
      ;;
    --stamp-product)
      _stamp_product
      ;;
    "" )
      echo "version $MEET_VERSION  build $MEET_BUILD"
      ;;
    *)
      echo "error: unknown argument: $1" >&2
      echo "usage: $0 [--check X.Y.Z|--export|--print|--write-xcconfig|--stamp-plist|--stamp-product]" >&2
      exit 1
      ;;
  esac
fi
