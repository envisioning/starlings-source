#!/usr/bin/env node
/**
 * Regenerate the doc map in `AGENTS.md` from `docs/**\/*.md` frontmatter
 * (docs/DOCUMENTATION.md, decision 2;). The table between the
 * `<!-- doc-map:start -->` and `<!-- doc-map:end -->` markers is generated;
 * hand edits there are overwritten.
 *
 *   node scripts/gen-doc-map.mjs           # write
 *   node scripts/gen-doc-map.mjs --check   # exit 1 when AGENTS.md is stale
 *
 * A doc's row comes from its `summary`; which table it lands in comes from
 * `kind` and `status`. To change the map, change the doc's frontmatter.
 *
 * Also writes `packages/contracts/src/help-index.json`: every active page
 * under docs/help/ and docs/help/howto/ with the capability ids it covers. The Worker
 * reads it to end each MCP tool description with the help pages for the
 * capabilities that tool reaches; the web /help site reads the
 * docs themselves at build time.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { KIND_LABEL, STATUS_MEANING, readAllDocs } from './docs-frontmatter.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(repoRoot, 'AGENTS.md');
const helpIndexTarget = join(repoRoot, 'packages', 'contracts', 'src', 'help-index.json');
const START = '<!-- doc-map:start -->';
const END = '<!-- doc-map:end -->';

const docs = readAllDocs(repoRoot);
const broken = docs.filter((doc) => doc.errors.length > 0);
if (broken.length > 0) {
  for (const doc of broken) console.error(`${doc.path}: ${doc.errors.join('; ')}`);
  console.error('fix the frontmatter first (scripts/check-docs.mjs)');
  process.exit(1);
}

const cell = (text) => text.replace(/\|/gu, '\\|');
const row = (doc) => `| \`${doc.path}\` | ${cell(doc.fields.summary)} |`;
const table = (rows) => ['| Doc | When you need it |', '| --- | --- |', ...rows].join('\n');

const current = docs.filter((doc) => doc.fields.status === 'active');
const sections = [];
for (const kind of ['contract', 'reference', 'howto', 'intent']) {
  const rows = current.filter((doc) => doc.fields.kind === kind).map(row);
  if (rows.length > 0) sections.push(`**${KIND_LABEL[kind]}**\n\n${table(rows)}`);
}
for (const status of ['proposed', 'done', 'superseded']) {
  const rows = docs.filter((doc) => doc.fields.status === status).map(row);
  if (rows.length > 0) sections.push(`**${status[0].toUpperCase()}${status.slice(1)}** — ${STATUS_MEANING[status]}.\n\n${table(rows)}`);
}

const generated = [
  START,
  'Generated by `scripts/gen-doc-map.mjs` from each doc\'s frontmatter; `pnpm verify` fails when it is stale. Edit the doc, not this table.',
  '',
  `Active docs first, by kind (${STATUS_MEANING.active}); then the proposed, done and superseded ones.`,
  '',
  sections.join('\n\n'),
  END,
].join('\n');

const helpIndex = `${JSON.stringify({
  $comment: 'Generated by scripts/gen-doc-map.mjs from docs/ frontmatter. Do not edit.',
  pages: docs
    // Product docs live under docs/help/ and docs/help/howto/. A runbook or
    // a map elsewhere may share the kind; it is not a help page.
    .filter((doc) => doc.fields.status === 'active' && /^docs\/help\//u.test(doc.path))
    .map((doc) => ({
      slug: doc.path.replace(/^docs\/help\//u, '').replace(/\.md$/u, ''),
      kind: doc.fields.kind,
      summary: doc.fields.summary,
      ...(doc.fields.surface ? { surface: doc.fields.surface } : {}),
      capabilities: doc.fields.capabilities ?? [],
    })),
}, null, 2)}\n`;

const text = readFileSync(target, 'utf8');
const start = text.indexOf(START);
const end = text.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`AGENTS.md needs the ${START} and ${END} markers under ## Doc map`);
  process.exit(1);
}
const next = text.slice(0, start) + generated + text.slice(end + END.length);

const currentHelpIndex = existsSync(helpIndexTarget) ? readFileSync(helpIndexTarget, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (next !== text || currentHelpIndex !== helpIndex) {
    console.error('AGENTS.md doc map or packages/contracts/src/help-index.json is stale: run pnpm docs:map and commit the result');
    process.exit(1);
  }
} else {
  if (next !== text) {
    writeFileSync(target, next);
    console.log('AGENTS.md doc map written');
  }
  if (currentHelpIndex !== helpIndex) {
    writeFileSync(helpIndexTarget, helpIndex);
    console.log('help-index.json written');
  }
}
