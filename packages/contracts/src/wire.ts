/**
 * A value set is open by default: a Swift client decodes a value it has never
 * seen as itself, because a native build is always older than the Worker. A
 * set the client itself chooses from (which surface it is, where a note is
 * filed) is `closed`: a real Swift enum, exhaustive switches, and a new
 * member arrives with the build that can act on it.
 */
export type WireEntry =
  | z.ZodType
  | { schema: z.ZodType; closed: true }
  /**
   * A request body: emitted as what a client may send (`io: 'input'`), so
   * a defaulted field is optional. Its Swift struct carries its own Codable,
   * with `Patch<T>` for a `.nullable().optional()` field (omit, null, value).
   */
  | { schema: z.ZodType; io: 'input' }
  /**
   * A GET's query string: emitted as what the Worker reads after coercion
   * (numbers, `z.stringbool()` booleans), with a defaulted field optional.
   * Its Swift struct is not Codable; it has `queryItems`, in the contract's
   * order, a nil field left out.
   */
  | { schema: z.ZodType; io: 'query' };

