/** One row by id, or undefined. */
export function capabilityById(id: string): Capability | undefined {
  return CAPABILITIES.find((row) => row.id === id);
}

export type CapabilitySection = { id: CapabilitySectionId; title: string; rows: Capability[] };

/** Every section with its rows, in page order. `pick` narrows the rows; empty sections are dropped. */
export function capabilitySections(pick: (row: Capability) => boolean = () => true): CapabilitySection[] {
  return CAPABILITY_SECTIONS
    .map((section) => ({ ...section, rows: CAPABILITIES.filter((row) => row.section === section.id && pick(row)) }))
    .filter((section) => section.rows.length > 0);
}

/** The rows with a build state on some surface — the "where can I do it" snapshot. */
export function surfaceSections(): CapabilitySection[] {
  return capabilitySections((row) => row.surfaces !== undefined);
}

/** How many rows hold each stance. */
export function countByIntent(rows: Capability[] = CAPABILITIES): Record<CapabilityIntent, number> {
  const counts: Record<CapabilityIntent, number> = { have: 0, partial: 0, want: 0, 'dont-want': 0, tbd: 0 };
  for (const row of rows) counts[row.intent] += 1;
  return counts;
}

/** The rows an agent can reach, and through which doors. A `humanOnly`, `gap` or `rule` row is not one. */
export function agentReachable(): Capability[] {
  return CAPABILITIES.filter((row) => hasAgentDoor(row.agent));
}
