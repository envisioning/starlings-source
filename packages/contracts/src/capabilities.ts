/** The door kinds an agent can have into a capability. */
export const AGENT_DOOR_KINDS = ['mcpTools', 'mcpResources', 'routes', 'signedRoutes', 'cli'] as const;

/**
 * How an agent reaches a capability: its doors, or `humanOnly`, or `gap`, or
 * `rule`, and never two of them. Every door named here must exist; the tests check.
 */
export const agentDoorsSchema = z.object({
  /** MCP tool names as `tools/list` returns them with `read write` scope. */
  mcpTools: z.array(z.string().min(1)).optional(),
  /** MCP resource URI templates as `resources/templates/list` returns them. */
  mcpResources: z.array(z.string().startsWith('starlings://')).optional(),
  /** Worker routes an agent with a bearer may call directly. */
  routes: z.array(z.string().startsWith('/api/')).optional(),
  /** HMAC-only internal callbacks; agents do not receive member bearer tokens. */
  signedRoutes: z.array(z.string().startsWith('/api/')).optional(),
  /** `starlings` verbs on the Mac (docs/OPERATIONS.md). */
  cli: z.array(z.string().startsWith('starlings ')).optional(),
  /** No agent should operate this: why, in one line. */
  humanOnly: z.string().min(1).optional(),
  /** An agent should reach this and cannot yet: the `envisioning/starlings` issue for the door. */
  gap: z.number().int().positive().optional(),
  /** Built in: a rule the server or the client holds, with nothing to operate. Why, in one line. */
  rule: z.string().min(1).optional(),
}).strict().superRefine((agent, context) => {
  const answers = [hasAgentDoor(agent), agent.humanOnly !== undefined, agent.gap !== undefined, agent.rule !== undefined].filter(Boolean).length;
  if (answers !== 1) context.addIssue({ code: 'custom', message: 'agent gives exactly one of: doors, humanOnly, gap, rule' });
});
export type AgentDoors = z.infer<typeof agentDoorsSchema>;

/** True when the row names at least one door, not `humanOnly`, `gap` or `rule`. */
export function hasAgentDoor(agent: AgentDoors | undefined): boolean {
  return agent !== undefined && AGENT_DOOR_KINDS.some((kind) => (agent[kind]?.length ?? 0) > 0);
}

export const capabilitySchema = z.object({
  /** Stable slug. `docs/help/` pages and `llms.txt` key on it; do not rename. */
  id: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/u),
  name: z.string().min(1),
  section: z.enum(sectionIds),
  intent: capabilityIntentSchema,
  /** The name peer products use, when it differs from ours. Search matches it. */
  peer: z.string().min(1).optional(),
  surfaces: z.record(capabilitySurfaceSchema, surfaceStatusSchema).optional(),
  /** The doc that owns the capability, relative to the repo root. */
  doc: z.string().regex(/^docs\/.+\.md$/u).optional(),
  agent: agentDoorsSchema.optional(),
  /** The `envisioning/starlings` issue that tracks the gap, for `want` / `partial` / `tbd` rows. */
  issue: z.number().int().positive().optional(),
  description: z.string().min(1),
}).strict();
export type Capability = z.infer<typeof capabilitySchema>;

