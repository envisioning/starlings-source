/**
 * The capability registry — what Meet does, in one place (docs/DOCUMENTATION.md,
 * decision 1;).
 *
 * One row per capability. Two facts per row that used to live in two files:
 *
 * - `intent`: the product stance, including things we do not want. This is the
 *   peer-product comparison that `/workspace/status` renders first.
 * - `surfaces`: where it works today, per client. Absent on a row nothing is
 *   built for. This is the "where can I do it" snapshot.
 *
 * And one fact that was nowhere: `agent`, how an agent reaches the
 * capability. Exactly one of four answers:
 *
 * - the doors: MCP tools and resources (`services/control-plane/src/mcp.ts`),
 *   Worker routes, `starlings` verbs (`CLI/StarlingsCLI.swift`);
 * - `humanOnly`: no agent should operate it, with the reason in one line;
 * - `rule`: built in, a rule the server or the client holds, with nothing for
 *   a person or an agent to operate; the reason in one line;
 * - `gap`: an agent should reach it and cannot yet; the `envisioning/starlings`
 *   issue that tracks the door. The gaps are the list of doors still to build
 *   (docs/AGENTS_SURFACE.md).
 *
 * Every `have` and `partial` row gives one of the four; the tests check.
 *
 * Not the Worker's `capabilities.ts`, which is what a *role* may do. This file
 * is what the *product* does.
 *
 * `web/src/FeaturesPage.tsx` and `FeatureStatusPage.tsx` read this; the tests
 * in `web/src/capabilities.test.ts` and `services/control-plane/test/mcp-capabilities.test.ts`
 * keep it honest — every named tool, resource and doc must exist.
 */

