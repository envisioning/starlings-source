#!/usr/bin/env node
/**
 * Write `schema/wire.json`: one JSON Schema `$defs` entry per row of
 * `src/wire.ts`, from zod's own emitter. Committed output, so the Swift
 * generator and any future Kotlin one read a file, not a Node process.
 *
 *   pnpm contracts:emit           # write
 *   pnpm contracts:emit --check   # exit 1 when the file on disk is stale
 *
 * Two passes over one registry. Responses are emitted with `io: 'output'`:
 * the native clients decode what the Worker sends, where transforms and
 * defaults are already applied. Request bodies (`io: 'input'` in wire.ts)
 * are emitted with `io: 'input'`: what a client may send, where a defaulted
 * field is optional. `$ref`s between rows come out as `#/$defs/<Name>` when
 * the same schema object is registered under a name, which is how nested
 * shapes stay one Swift type in either pass.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { type WireEntry, wireSchemas } from '../src/wire.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'schema', 'wire.json');

/** The `wire.json` document for a registry: both passes, one `$defs`. */
export function buildWireDocument(schemas: Record<string, WireEntry>) {
  const entries = Object.entries(schemas).map(([name, entry]) =>
    entry instanceof z.ZodType
      ? { name, schema: entry, closed: false, io: 'output' as const }
      : { name, schema: entry.schema, closed: 'closed' in entry, io: 'io' in entry ? entry.io : ('output' as const) },
  );
  const registry = z.registry<{ id: string }>();
  for (const { name, schema } of entries) registry.add(schema, { id: name });

  // Each pass walks the whole registry (that is what makes `$ref`s resolve), so
  // a request body's transform, which has no output shape, must not throw in the
  // output pass. It comes out as `{}` there, and that def is not the one taken.
  const pass = (io: 'input' | 'output') =>
    z.toJSONSchema(registry, { io, uri: (id) => `#/$defs/${id}`, unrepresentable: 'any' }).schemas;
  const passes = { output: pass('output'), input: pass('input') };
  // A query string is read after coercion, so its types are the output pass's
  // (`z.coerce.number()` is a number, `z.stringbool()` a boolean), but a
  // client may leave a defaulted field out, so those are not required.
  const query = (def: Record<string, unknown>) => {
    const properties = (def.properties ?? {}) as Record<string, Record<string, unknown>>;
    const required = ((def.required ?? []) as string[]).filter((key) => !('default' in (properties[key] ?? {})));
    return { ...def, required };
  };
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $comment: 'Generated by packages/contracts/scripts/emit-schema.ts from src/wire.ts. Do not edit.',
    $defs: Object.fromEntries(
      entries.map(({ name, closed, io }) => {
        const { $schema: _schema, ...emitted } = passes[io === 'query' ? 'output' : io][name] as Record<string, unknown>;
        const def = io === 'query' ? query(emitted) : emitted;
        // Not JSON Schema vocabulary: `x-closed` tells the Swift emitter this
        // value set is a real enum; `x-io` that this shape is a request body
        // or a query string (see `WireEntry` in src/wire.ts).
        return [name, { ...def, ...(closed ? { 'x-closed': true } : {}), ...(io === 'output' ? {} : { 'x-io': io }) }];
      }),
    ),
  };
}

const document = buildWireDocument(wireSchemas);
const text = `${JSON.stringify(document, null, 2)}\n`;
if (!import.meta.main) {
  // Imported by the test; nothing to write.
} else if (process.argv.includes('--check')) {
  // The gate: what is on disk must be what the schemas say now.
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== text) {
    console.error(`${out} is stale: run pnpm contracts:gen and commit the result`);
    process.exit(1);
  }
  console.log(`${out} is current`);
} else {
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  console.log(`wrote ${Object.keys(document.$defs).length} shapes to ${out}`);
}
