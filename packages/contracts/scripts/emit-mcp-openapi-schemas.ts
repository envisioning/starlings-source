import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import {
  cmsTechnologyImageRequestSchema,
  decisionAskCreateSchema,
  decisionAsksQuerySchema,
  decisionAskWithdrawSchema,
  docsCreateDocumentSchema,
  docsDocumentResponseSchema,
  docsMoveDocumentSchema,
  docsSetSubjectsSchema,
  docsUpdateDocumentSchema,
  operationalErrorOverviewQuerySchema,
  operationalErrorOverviewSchema,
} from '../src/index.ts';
import {
  catalogResponseSchema,
  catalogServiceResponseSchema,
  catalogServiceSchema,
  offerCreateSchema,
  offerDecisionSchema,
  offerDuplicateSchema,
  offerHeaderSchema,
  offerLineCreateSchema,
  offerLinePatchSchema,
  offerLineSchema,
  offerOptionsResponseSchema,
  offerPatchSchema,
  offerResponseSchema,
  offerSendResponseSchema,
  offerTotalsSchema,
  offerVersionResponseSchema,
  offerVersionSummarySchema,
  organizationDiscountResponseSchema,
  organizationDiscountSchema,
  serviceCreateSchema,
  servicePatchSchema,
} from '../src/offers.ts';

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, '..', 'schema', 'mcp-openapi.json');
const schemas = {
  CmsTechnologyImageRequest: { schema: cmsTechnologyImageRequestSchema, io: 'input' as const },
  DocsDocumentResponse: { schema: docsDocumentResponseSchema, io: 'output' as const },
  DocsCreateDocument: { schema: docsCreateDocumentSchema, io: 'input' as const },
  DocsUpdateDocument: { schema: docsUpdateDocumentSchema, io: 'input' as const },
  DocsSetSubjects: { schema: docsSetSubjectsSchema, io: 'input' as const },
  DocsMoveDocument: { schema: docsMoveDocumentSchema, io: 'input' as const },
  DecisionAskCreate: { schema: decisionAskCreateSchema, io: 'input' as const },
  DecisionAskWithdraw: { schema: decisionAskWithdrawSchema, io: 'input' as const },
  DecisionAsksQuery: { schema: decisionAsksQuerySchema, io: 'input' as const },
  OperationalErrorOverviewQuery: { schema: operationalErrorOverviewQuerySchema, io: 'input' as const },
  OperationalErrorOverview: { schema: operationalErrorOverviewSchema, io: 'output' as const },
  OfferCreate: { schema: offerCreateSchema, io: 'input' as const },
  OfferPatch: { schema: offerPatchSchema, io: 'input' as const },
  OfferLineCreate: { schema: offerLineCreateSchema, io: 'input' as const },
  OfferLinePatch: { schema: offerLinePatchSchema, io: 'input' as const },
  OfferDuplicate: { schema: offerDuplicateSchema, io: 'input' as const },
  OfferDecision: { schema: offerDecisionSchema, io: 'input' as const },
  OrganizationDiscount: { schema: organizationDiscountSchema, io: 'input' as const },
  ServiceCreate: { schema: serviceCreateSchema, io: 'input' as const },
  ServicePatch: { schema: servicePatchSchema, io: 'input' as const },
  OfferResponse: { schema: offerResponseSchema, io: 'output' as const },
  OfferSendResponse: { schema: offerSendResponseSchema, io: 'output' as const },
  OfferVersionResponse: { schema: offerVersionResponseSchema, io: 'output' as const },
  OfferOptionsResponse: { schema: offerOptionsResponseSchema, io: 'output' as const },
  OrganizationDiscountResponse: { schema: organizationDiscountResponseSchema, io: 'output' as const },
  OfferHeader: { schema: offerHeaderSchema, io: 'output' as const },
  OfferLine: { schema: offerLineSchema, io: 'output' as const },
  OfferTotals: { schema: offerTotalsSchema, io: 'output' as const },
  OfferVersionSummary: { schema: offerVersionSummarySchema, io: 'output' as const },
  CatalogService: { schema: catalogServiceSchema, io: 'output' as const },
  CatalogResponse: { schema: catalogResponseSchema, io: 'output' as const },
  CatalogServiceResponse: { schema: catalogServiceResponseSchema, io: 'output' as const },
};

const registry = z.registry<{ id: string }>();
for (const [id, entry] of Object.entries(schemas)) registry.add(entry.schema, { id });
const pass = (io: 'input' | 'output') => z.toJSONSchema(registry, {
  io,
  uri: (id) => `#/$defs/${id}`,
  unrepresentable: 'any',
}).schemas;
const emitted = Object.fromEntries(Object.entries(schemas).map(([id, entry]) => [
  id,
  pass(entry.io)[id],
]));
const document = `${JSON.stringify({
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $comment: 'Generated by packages/contracts/scripts/emit-mcp-openapi-schemas.ts from contract Zod schemas. Do not edit.',
  $defs: emitted,
}, null, 2)}\n`;

if (!import.meta.main) {
  // Imported by tooling without writing output.
} else if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current !== document) {
    console.error(`${output} is stale: run pnpm openapi:gen and commit the result`);
    process.exitCode = 1;
  } else {
    console.log(`${output} is current`);
  }
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, document);
  console.log(`wrote ${Object.keys(emitted).length} additional MCP API schemas`);
}
