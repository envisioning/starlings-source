/** Keep's settings inside Keep (`KeepSettingsView`): the ways this key unlocks and, with it open, recovery. */
@Composable
internal fun KeepSettingsScreen(session: KeepSession, onBack: () -> Unit) {
    LaunchedEffect(Unit) { session.touch() }
    Column(Modifier.fillMaxSize().background(Starlings.colors.canvas)) {
        WorkTopBar(stringResource(R.string.keep_settings_title), stringResource(R.string.back), onBack)
        Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(16.dp), verticalArrangement = Arrangement.spacedBy(18.dp)) {
            KeepUnlockMethods(session)
            if (session.isUnlocked) KeepRecoverySections(session)
        }
    }
}

/**
 * Keep in the app's Settings (`MobileKeepSettingsSection`): the same rows
 * Keep's own settings show (with the key open, Recovery too), once the
 * token is there. There is no connection row: the token comes with the
 * Starlings session. Draws nothing where the workspace has no Keep.
 */
@Composable
fun KeepSettingsSections() {
    val context = LocalContext.current
    val access = remember { KeepAccess.of(context) }
    if (!access.isLinked) return
    KeepUnlockMethods(access.session)
    if (access.session.isUnlocked) KeepRecoverySections(access.session)
}

/**
 * The unlock-method rows (`KeepUnlockMethodsSections`). Needs the key open;
 * says why when it is not. The key is open here, so it can be sealed again
 * under a new passphrase or a passkey. The Passkey section shows only where
 * [KeepPasskey.isAvailable], as on iOS.
 */
@Composable
internal fun KeepUnlockMethods(session: KeepSession) {
    val c = Starlings.colors
    val context = LocalContext.current
    var passphrase by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<String?>(null) }
    var error by remember { mutableStateOf<String?>(null) }
    var done by remember { mutableStateOf<String?>(null) }
    LaunchedEffect(session) { if (session.me == null) session.refresh() }

    if (!session.isUnlocked) {
        ListSection(stringResource(R.string.keep_title)) {
            ListRow {
                Text(
                    stringResource(if (session.me == null) R.string.keep_methods_connect else R.string.keep_methods_unlock),
                    style = StarlingsType.footnote,
                    color = c.secondary,
                )
            }
        }
        return
    }
    val hasPassphrase = session.hasPassphrase
    val hasPasskey = session.passkeyCredentialId != null
    val problem = when {
        passphrase.isEmpty() -> null
        passphrase.length < 12 -> stringResource(R.string.keep_twelve_minimum)
        confirm != passphrase -> stringResource(if (confirm.isEmpty()) R.string.keep_type_again else R.string.keep_do_not_match)
        else -> null
    }
    val passkeyAvailable = remember(context) { KeepPasskey.isAvailable(context) }
    val saved = stringResource(R.string.keep_passphrase_saved)
    val passkeySaved = stringResource(R.string.keep_passkey_saved)
    val copiedStore = stringResource(R.string.keep_copied_store)

    Column {
        ListSection(stringResource(R.string.keep_unlocks_with)) {
            WorkLabeledRow(stringResource(R.string.keep_passkey), stringResource(if (hasPasskey) R.string.keep_yes else R.string.keep_no))
            WorkDivider()
            WorkLabeledRow(stringResource(R.string.keep_passphrase), stringResource(if (hasPassphrase) R.string.keep_yes else R.string.keep_no))
            WorkDivider()
            ListRow { Text(stringResource(R.string.keep_mac_needs_passphrase), style = StarlingsType.footnote, color = c.secondary) }
        }
    }
    Column {
        ListSection(stringResource(if (hasPassphrase) R.string.keep_change_passphrase else R.string.keep_add_passphrase)) {
            ListRow(divider = true) { KeepSecretField(stringResource(R.string.keep_passphrase), passphrase, { passphrase = it }) }
            ListRow(divider = true) { KeepSecretField(stringResource(R.string.keep_again), confirm, { confirm = it }) }
            generated?.let { value ->
                ListRow(divider = true) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(Modifier.weight(1f)) {
                            SelectionContainer { Text(value, style = StarlingsType.body.copy(fontFamily = FontFamily.Monospace), color = c.primary) }
                        }
                        KeepLinkButton(stringResource(R.string.keep_copy), Icons.Outlined.ContentCopy) {
                            copySecret(context, context.getString(R.string.keep_passphrase), value)
                            done = copiedStore
                        }
                    }
                }
            }
            ListRow {
                problem?.let { Text(it, style = StarlingsType.footnote, color = c.secondary) }
                Row(horizontalArrangement = Arrangement.spacedBy(16.dp), verticalAlignment = Alignment.CenterVertically) {
                    TextButton({
                        val value = KeepPassphrase.generate()
                        generated = value
                        passphrase = value
                        confirm = value
                        done = null
                    }) { Text(stringResource(R.string.keep_generate_one), color = c.accent) }
                }
                KeepAsyncButton(
                    stringResource(if (hasPassphrase) R.string.keep_change_passphrase else R.string.keep_save_passphrase),
                    icon = Icons.Outlined.Lock,
                    enabled = passphrase.isNotEmpty() && problem == null,
                ) {
                    error = null
                    done = null
                    try {
                        session.addPassphrase(passphrase)
                        passphrase = ""
                        confirm = ""
                        done = saved
                    } catch (e: CancellationException) {
                        throw e
                    } catch (e: Exception) {
                        error = e.message
                    }
                }
            }
        }
        Text(stringResource(R.string.keep_passphrase_footer), Modifier.padding(horizontal = 16.dp, vertical = 6.dp), style = StarlingsType.footnote, color = c.secondary)
    }
    if (passkeyAvailable) {
        Column {
            ListSection(stringResource(R.string.keep_passkey)) {
                ListRow {
                    KeepAsyncButton(
                        stringResource(if (hasPasskey) R.string.keep_replace_passkey else R.string.keep_add_passkey),
                        icon = Icons.Outlined.Key,
                    ) {
                        error = null
                        done = null
                        val me = session.me ?: return@KeepAsyncButton
                        try {
                            val enrolment = keepPasskey(context, session).enrol(me.email, me.name)
                            try {
                                session.addPasskey(enrolment)
                            } finally {
                                enrolment.prf.fill(0)
                            }
                            done = passkeySaved
                        } catch (e: CancellationException) {
                            throw e
                        } catch (_: KeepPasskeyError.Cancelled) {
                            // Nothing to say.
                        } catch (e: Exception) {
                            error = e.message
                        }
                    }
                }
            }
            Text(stringResource(R.string.keep_passkey_footer), Modifier.padding(horizontal = 16.dp, vertical = 6.dp), style = StarlingsType.footnote, color = c.secondary)
        }
    }
    if (done != null || error != null) {
        Column(Modifier.fillMaxWidth().padding(horizontal = 16.dp)) {
            done?.let { Text(it, style = StarlingsType.footnote, color = c.secondary) }
            KeepErrorText(error)
        }
    }
}
